"""hearth-boot-move (1.11): a PC moved from the Fedora edition gets Hearth's own boot menu. The careful parts checked
here; the whole move is proven in a virtual PC (boot-look-vm.sh step 8: Fedora's loader, it starts, the move, it
starts through Debian's GRUB)."""
import importlib.machinery
import importlib.util
import os
import shutil
import tempfile
import unittest
from unittest import mock

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
TOOL = os.path.join(ROOT, 'os-bases/peppermint/system_files/usr/libexec/nimbus/hearth-boot-move')
loader = importlib.machinery.SourceFileLoader('hearth_boot_move', TOOL)
spec = importlib.util.spec_from_loader('hearth_boot_move', loader)
bm = importlib.util.module_from_spec(spec)
loader.exec_module(bm)


class Detect(unittest.TestCase):
    def test_fedora_loader(self):
        self.assertTrue(bm.fedora_loader('anatase-1,grub2-1:2.12-82.fc45,shim-16.1-7'))     # the owner's Nvidia PC
        self.assertFalse(bm.fedora_loader('grub2-1+2.12+9+deb13u2,shim-1.51_1+deb13u1+16.1-2_deb13u1'))

    def test_check_never_changes_anything_and_needs_debian(self):
        st = {'components': {'EFI': {'installed': {'version': 'anatase-1,grub2-1:2.12-82.fc45'}}}}
        with mock.patch.object(bm, 'bootupd_status', return_value=st), mock.patch.object(bm, 'edition', return_value=('hearth-peppermint', True)):
            self.assertTrue(bm.check()['needed'])
        with mock.patch.object(bm, 'bootupd_status', return_value=st), mock.patch.object(bm, 'edition', return_value=('', False)):
            self.assertFalse(bm.check()['needed'])

    def test_run_refuses_without_yes_and_root(self):
        with mock.patch.object(bm.os, 'geteuid', return_value=1000):
            with self.assertRaises(bm.Fail):
                bm.run(True)


class StaticMenu(unittest.TestCase):
    def setUp(self):
        self.d = tempfile.mkdtemp()
        os.makedirs(os.path.join(self.d, 'configs.d'))
        open(os.path.join(self.d, 'grub-static-pre.cfg'), 'w').write('set timeout=5\n')
        shutil.copy(os.path.join(ROOT, 'os-bases/peppermint/system_files/usr/lib/bootupd/grub2-static/configs.d/10_blscfg.cfg'),
                    os.path.join(self.d, 'configs.d', '10_blscfg.cfg'))
        open(os.path.join(self.d, 'configs.d', '41_custom.cfg'), 'w').write('source $prefix/custom.cfg\n')

    def tearDown(self):
        shutil.rmtree(self.d)

    def test_like_bootupd_and_without_blscfg(self):
        with mock.patch.object(bm, 'STATIC', self.d):
            t = bm.static_cfg()
        self.assertTrue(t.startswith('# Generated by bootupd / do not edit\n\nset timeout=5\n'))
        self.assertIn('### BEGIN 10_blscfg.cfg ###', t)
        self.assertLess(t.index('10_blscfg'), t.index('41_custom'))
        self.assertIn('hearth-bls.cfg', t)

    def test_refuses_a_menu_that_still_says_blscfg(self):
        open(os.path.join(self.d, 'configs.d', '10_blscfg.cfg'), 'w').write('blscfg\n')
        with mock.patch.object(bm, 'STATIC', self.d):
            with self.assertRaises(bm.Fail):
                bm.static_cfg()


class Ci(unittest.TestCase):
    def test_the_virtual_pc_proves_it(self):
        s = open(os.path.join(ROOT, '.github/scripts/boot-look-vm.sh')).read()
        for want in ('boot fedora-before yes', 'hearth-boot-move run --yes', 'boot after-move yes', 'EFI/hearth-fedora/shimx64.efi'):
            self.assertIn(want, s)


if __name__ == '__main__':
    unittest.main()
