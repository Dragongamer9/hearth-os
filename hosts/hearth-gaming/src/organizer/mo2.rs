//! Mod Organizer 2's own files, read and written the way MO2 does (github.com/ModOrganizer2/modorganizer,
//! GPL-3.0), so an instance works in both MO2 and Hearth:
//! - ModOrganizer.ini and each mod's meta.ini: Qt's ini format (@ByteArray(...), doubled backslashes);
//! - a profile's modlist.txt: one mod per line, highest priority first; + on, - off, * unmanaged (DLC);
//! - plugins.txt: * before active plugins (Skyrim SE, Fallout 4), or just the active ones (older games) with
//!   loadorder.txt for the order;
//! - settings.ini of a profile: LocalSaves and LocalSettings.

use std::path::{Path, PathBuf};

pub const HEADER: &str = "# This file was automatically generated by Mod Organizer.";

// ------------------------------------------------------------------ ini files

/// An ini file: sections in order, keys in order (a key set twice keeps its last value, as Qt reads it).
#[derive(Debug, Clone, Default, PartialEq)]
pub struct Ini { pub sections: Vec<(String, Vec<(String, String)>)> }

impl Ini {
    pub fn parse(text: &str) -> Ini {
        let mut ini = Ini::default();
        let mut cur: Option<usize> = None;
        for line in text.trim_start_matches('\u{feff}').lines() {
            let t = line.trim();
            if t.is_empty() || t.starts_with(';') || t.starts_with('#') { continue; }
            if t.starts_with('[') && t.ends_with(']') {
                let name = t[1..t.len() - 1].trim().to_string();
                cur = Some(match ini.sections.iter().position(|s| s.0.eq_ignore_ascii_case(&name)) {
                    Some(i) => i,
                    None => { ini.sections.push((name, Vec::new())); ini.sections.len() - 1 }
                });
                continue;
            }
            let Some((k, v)) = t.split_once('=') else { continue };
            let i = match cur { Some(i) => i, None => { ini.sections.push(("General".into(), Vec::new())); cur = Some(ini.sections.len() - 1); ini.sections.len() - 1 } };
            let (k, v) = (k.trim().to_string(), v.trim().to_string());
            let sec = &mut ini.sections[i].1;
            match sec.iter_mut().find(|e| e.0.eq_ignore_ascii_case(&k)) { Some(e) => e.1 = v, None => sec.push((k, v)) }
        }
        ini
    }
    pub fn read(path: &Path) -> Ini { std::fs::read(path).map(|b| Ini::parse(&String::from_utf8_lossy(&b))).unwrap_or_default() }
    /// The raw value.
    pub fn raw(&self, section: &str, key: &str) -> Option<&str> {
        self.sections.iter().find(|s| s.0.eq_ignore_ascii_case(section))?.1.iter().find(|e| e.0.eq_ignore_ascii_case(key)).map(|e| e.1.as_str())
    }
    /// The value as Qt means it (quotes, escapes and @ByteArray taken off).
    pub fn get(&self, section: &str, key: &str) -> Option<String> { self.raw(section, key).map(qt_value) }
    pub fn get_bool(&self, section: &str, key: &str) -> Option<bool> { self.get(section, key).map(|v| v.eq_ignore_ascii_case("true") || v == "1") }
    pub fn set_raw(&mut self, section: &str, key: &str, value: &str) {
        let i = match self.sections.iter().position(|s| s.0.eq_ignore_ascii_case(section)) { Some(i) => i, None => { self.sections.push((section.into(), Vec::new())); self.sections.len() - 1 } };
        let sec = &mut self.sections[i].1;
        match sec.iter_mut().find(|e| e.0.eq_ignore_ascii_case(key)) { Some(e) => e.1 = value.into(), None => sec.push((key.into(), value.into())) }
    }
    pub fn set(&mut self, section: &str, key: &str, value: &str) { self.set_raw(section, key, &qt_escape(value)); }
    pub fn keys(&self, section: &str) -> Vec<(String, String)> {
        self.sections.iter().find(|s| s.0.eq_ignore_ascii_case(section)).map(|s| s.1.clone()).unwrap_or_default()
    }
    pub fn to_text(&self) -> String {
        let mut out = String::new();
        for (name, keys) in &self.sections {
            out.push_str(&format!("[{name}]\r\n"));
            for (k, v) in keys { out.push_str(&format!("{k}={v}\r\n")); }
            out.push_str("\r\n");
        }
        out
    }
    pub fn write(&self, path: &Path) -> Result<(), String> {
        crate::util::write_atomic(path, self.to_text().as_bytes()).map_err(|e| format!("Couldn't write {} ({e})", path.display()))
    }
}

/// A Qt ini value as text: "quoted" values unquoted, \\ \" \n \t \xHHHH unescaped, @ByteArray(...) unwrapped.
pub fn qt_value(raw: &str) -> String {
    let mut s = raw.trim();
    if s.len() >= 2 && s.starts_with('"') && s.ends_with('"') { s = &s[1..s.len() - 1]; }
    let mut out = String::new();
    let mut it = s.chars().peekable();
    while let Some(c) = it.next() {
        if c != '\\' { out.push(c); continue; }
        match it.next() {
            Some('n') => out.push('\n'),
            Some('t') => out.push('\t'),
            Some('r') => out.push('\r'),
            Some('0') => out.push('\0'),
            Some('x') => {
                let mut hex = String::new();
                while hex.len() < 4 { match it.peek() { Some(h) if h.is_ascii_hexdigit() => { hex.push(*h); it.next(); } _ => break } }
                if let Some(ch) = u32::from_str_radix(&hex, 16).ok().and_then(char::from_u32) { out.push(ch); }
            }
            Some(o) => out.push(o),
            None => out.push('\\'),
        }
    }
    match out.strip_prefix("@ByteArray(").and_then(|r| r.strip_suffix(')')) { Some(inner) => inner.to_string(), None => out }
}
/// Text as a Qt ini value (backslashes and quotes escaped; quoted when it has a comma or ; or starts with a space).
pub fn qt_escape(v: &str) -> String {
    let e = v.replace('\\', "\\\\").replace('"', "\\\"");
    if e.contains(',') || e.contains(';') || e.starts_with(' ') || e.ends_with(' ') { format!("\"{e}\"") } else { e }
}
pub fn qt_bytearray(v: &str) -> String { format!("@ByteArray({})", v.replace('\\', "\\\\").replace('"', "\\\"")) }

/// Sets one key of an ini file in place (every other line kept as it is): the last copy of the key in the section,
/// or a new line under the section's header, or a new section. MO2 reads ModOrganizer.ini this way too.
pub fn set_in_file(path: &Path, section: &str, key: &str, raw_value: &str) -> Result<(), String> {
    let text = std::fs::read(path).map(|b| String::from_utf8_lossy(&b).to_string()).unwrap_or_default();
    let mut lines: Vec<String> = text.trim_start_matches('\u{feff}').lines().map(str::to_string).collect();
    let line = format!("{key}={raw_value}");
    let mut in_sec = false;
    let (mut header, mut last) = (None, None);
    for (i, l) in lines.iter().enumerate() {
        let t = l.trim();
        if t.starts_with('[') && t.ends_with(']') { in_sec = t[1..t.len() - 1].trim().eq_ignore_ascii_case(section); if in_sec && header.is_none() { header = Some(i); } continue; }
        if in_sec { if let Some((k, _)) = t.split_once('=') { if k.trim().eq_ignore_ascii_case(key) { last = Some(i); } } }
    }
    match (last, header) {
        (Some(i), _) => lines[i] = line,
        (None, Some(h)) => lines.insert(h + 1, line),
        (None, None) => { lines.push(format!("[{section}]")); lines.push(line); }
    }
    crate::util::write_atomic(path, (lines.join("\r\n") + "\r\n").as_bytes()).map_err(|e| format!("Couldn't write {} ({e})", path.display()))
}

// ------------------------------------------------------------------ Windows paths

/// A path from MO2's ini as a Linux path: Z:\home\a → /home/a; C:\… inside the prefix's drive_c (other letters
/// through the prefix's dosdevices links); a Linux path as it is. None when it can't be worked out.
pub fn win_to_linux(p: &str, prefix: Option<&Path>) -> Option<PathBuf> {
    let p = p.trim();
    if p.is_empty() { return None; }
    if p.starts_with('/') { return Some(PathBuf::from(p)); }
    let b = p.as_bytes();
    if b.len() < 2 || b[1] != b':' || !b[0].is_ascii_alphabetic() { return None; }
    let letter = (b[0] as char).to_ascii_lowercase();
    let rest: Vec<&str> = p[2..].split(['\\', '/']).filter(|s| !s.is_empty()).collect();
    let base = match letter {
        'z' => PathBuf::from("/"),
        'c' => prefix?.join("drive_c"),
        _ => { let link = prefix?.join("dosdevices").join(format!("{letter}:")); std::fs::canonicalize(link).ok()? }
    };
    let mut out = base;
    for r in rest { if r == ".." { return None; } out.push(r); }
    Some(out)
}
/// A Linux path as MO2 writes it under Wine (Z:\home\a).
pub fn linux_to_win(p: &Path) -> String { format!("Z:{}", p.to_string_lossy().replace('/', "\\")) }

// ------------------------------------------------------------------ modlist.txt

#[derive(Debug, Clone, PartialEq)]
pub struct ModLine { pub name: String, pub state: char }

/// modlist.txt as MO2 writes it, highest priority first; returned lowest first (index = priority).
pub fn parse_modlist(text: &str) -> Vec<ModLine> {
    let mut v: Vec<ModLine> = text.trim_start_matches('\u{feff}').lines().filter_map(|l| {
        let l = l.trim_end_matches('\r');
        if l.trim().is_empty() || l.starts_with('#') { return None; }
        let mut c = l.chars();
        let st = c.next()?;
        if !matches!(st, '+' | '-' | '*') { return None; }
        let name = c.as_str().trim().to_string();
        if name.is_empty() { None } else { Some(ModLine { name, state: st }) }
    }).collect();
    v.reverse();
    // A mod listed twice: MO2 keeps the first (highest) one.
    let mut seen = std::collections::BTreeSet::new();
    let mut out: Vec<ModLine> = Vec::new();
    for m in v.into_iter().rev() { if seen.insert(m.name.to_lowercase()) { out.push(m); } }
    out.reverse();
    out
}
/// Lowest priority first → modlist.txt (highest first).
pub fn write_modlist(list: &[ModLine]) -> String {
    let mut out = format!("{HEADER}\r\n");
    for m in list.iter().rev() { out.push(m.state); out.push_str(&m.name); out.push_str("\r\n"); }
    out
}

// ------------------------------------------------------------------ plugins.txt and loadorder.txt

#[derive(Debug, Clone, PartialEq)]
pub struct PluginLine { pub name: String, pub active: bool }

pub fn parse_plugins(text: &str, star: bool) -> Vec<PluginLine> {
    text.trim_start_matches('\u{feff}').lines().filter_map(|l| {
        let l = l.trim();
        if l.is_empty() || l.starts_with('#') { return None; }
        if star { match l.strip_prefix('*') { Some(n) => Some(PluginLine { name: n.trim().into(), active: true }), None => Some(PluginLine { name: l.into(), active: false }) } }
        else { Some(PluginLine { name: l.into(), active: true }) }
    }).collect()
}
pub fn write_plugins(list: &[PluginLine], star: bool) -> String {
    let mut out = format!("{HEADER}\r\n");
    for p in list {
        if star { if p.active { out.push('*'); } out.push_str(&p.name); out.push_str("\r\n"); }
        else if p.active { out.push_str(&p.name); out.push_str("\r\n"); }
    }
    out
}
pub fn parse_loadorder(text: &str) -> Vec<String> {
    text.trim_start_matches('\u{feff}').lines().map(str::trim).filter(|l| !l.is_empty() && !l.starts_with('#')).map(str::to_string).collect()
}
pub fn write_loadorder(names: &[String]) -> String {
    let mut out = format!("{HEADER}\r\n");
    for n in names { out.push_str(n); out.push_str("\r\n"); }
    out
}

/// A mod or profile name that's safe as a folder name (MO2 refuses the same characters).
pub fn clean_name(n: &str) -> String {
    let s: String = n.chars().map(|c| if matches!(c, '/' | '\\' | ':' | '*' | '?' | '"' | '<' | '>' | '|') || c.is_control() { ' ' } else { c }).collect();
    let s = s.split_whitespace().collect::<Vec<_>>().join(" ");
    let s = s.trim_matches('.').trim().chars().take(160).collect::<String>();
    if s.is_empty() { "Mod".into() } else { s }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn modlist_round_trip() {
        let text = "# This file was automatically generated by Mod Organizer.\r\n+Top Mod\r\n-Off Mod\r\n*DLC: Dawnguard\r\n+Bottom Mod\r\n+Top Mod\r\n";
        let l = parse_modlist(text);
        // Lowest priority first; the second "Top Mod" (lower in the file) is dropped.
        assert_eq!(l.iter().map(|m| m.name.as_str()).collect::<Vec<_>>(), vec!["Bottom Mod", "DLC: Dawnguard", "Off Mod", "Top Mod"]);
        assert_eq!(l[0].state, '+');
        assert_eq!(l[1].state, '*');
        assert_eq!(l[2].state, '-');
        let out = write_modlist(&l);
        assert_eq!(out, "# This file was automatically generated by Mod Organizer.\r\n+Top Mod\r\n-Off Mod\r\n*DLC: Dawnguard\r\n+Bottom Mod\r\n");
        assert_eq!(parse_modlist(&out), l);
    }

    #[test]
    fn plugins_round_trip() {
        let star = "# x\r\n*Unofficial Skyrim Special Edition Patch.esp\r\nOff.esp\r\n*Light.esl\r\n";
        let p = parse_plugins(star, true);
        assert_eq!(p, vec![PluginLine { name: "Unofficial Skyrim Special Edition Patch.esp".into(), active: true }, PluginLine { name: "Off.esp".into(), active: false }, PluginLine { name: "Light.esl".into(), active: true }]);
        assert_eq!(parse_plugins(&write_plugins(&p, true), true), p);
        // Older games: only the active ones are listed; loadorder.txt has them all.
        let old = write_plugins(&p, false);
        assert!(!old.contains("Off.esp") && old.contains("Light.esl"));
        assert!(parse_plugins(&old, false).iter().all(|x| x.active));
        let lo = write_loadorder(&["A.esm".into(), "B.esp".into()]);
        assert_eq!(parse_loadorder(&lo), vec!["A.esm", "B.esp"]);
    }

    #[test]
    fn ini_values() {
        let ini = Ini::parse("\u{feff}[General]\r\ngameName=Skyrim Special Edition\r\ngamePath=@ByteArray(Z:\\\\home\\\\you\\\\Skyrim Special Edition)\r\nselected_profile=@ByteArray(Default)\r\n[customExecutables]\r\nsize=1\r\n1\\title=SKSE\r\n1\\binary=Z:/home/you/Skyrim Special Edition/skse64_loader.exe\r\n[General]\r\ngameName = Skyrim Special Edition\r\n");
        assert_eq!(ini.get("General", "gamePath").as_deref(), Some("Z:\\home\\you\\Skyrim Special Edition"));
        assert_eq!(ini.get("general", "selected_profile").as_deref(), Some("Default"));
        assert_eq!(ini.get("customExecutables", "1\\title").as_deref(), Some("SKSE"));
        assert_eq!(qt_value("\"a, b\""), "a, b");
        assert_eq!(qt_value("caf\\xe9"), "café");
        assert_eq!(qt_value(&qt_bytearray("C:\\Games\\x")), "C:\\Games\\x");
        let mut i2 = ini.clone();
        i2.set("General", "selected_profile", "Survival");
        assert_eq!(Ini::parse(&i2.to_text()).get("General", "selected_profile").as_deref(), Some("Survival"));
    }

    #[test]
    fn ini_lines_set_in_place() {
        let t = tempfile::tempdir().unwrap();
        let f = t.path().join("ModOrganizer.ini");
        std::fs::write(&f, "[General]\r\ngameName=Fallout 4\r\nselected_profile=@ByteArray(Default)\r\n[Settings]\r\nx=1\r\n").unwrap();
        set_in_file(&f, "General", "selected_profile", &qt_bytearray("Other")).unwrap();
        set_in_file(&f, "Settings", "y", "2").unwrap();
        set_in_file(&f, "New", "z", "3").unwrap();
        let s = std::fs::read_to_string(&f).unwrap();
        assert!(s.contains("selected_profile=@ByteArray(Other)") && !s.contains("Default"), "{s}");
        assert!(s.contains("[Settings]\r\ny=2\r\nx=1") && s.ends_with("[New]\r\nz=3\r\n"), "{s}");
        assert!(s.contains("gameName=Fallout 4"));
    }

    #[test]
    fn windows_paths() {
        assert_eq!(win_to_linux("Z:\\home\\you\\Game", None), Some(PathBuf::from("/home/you/Game")));
        assert_eq!(win_to_linux("Z:/home/you/Game", None), Some(PathBuf::from("/home/you/Game")));
        assert_eq!(win_to_linux("C:\\Games\\X", Some(Path::new("/pfx"))), Some(PathBuf::from("/pfx/drive_c/Games/X")));
        assert_eq!(win_to_linux("C:\\Games\\X", None), None);
        assert_eq!(win_to_linux("Z:\\a\\..\\etc", None), None);
        assert_eq!(win_to_linux("/already/linux", None), Some(PathBuf::from("/already/linux")));
        assert_eq!(linux_to_win(Path::new("/home/a/G")), "Z:\\home\\a\\G");
        assert_eq!(clean_name("a/b: c?"), "a b c");
        assert_eq!(clean_name(".."), "Mod");
    }
}
